/**
 * Reference copies of the filter coefficient tables Phoenix used to ship.
 *
 * These tables were designed offline for a single audio sample rate of 24 ksps
 * (192 ksps at the ADC, decimated by 8). Production code now generates them at
 * run time from an analog spec so that they land on the same frequencies at any
 * sample rate - see InitializeReceiveAudioFilterCoeffs() and
 * InitializeTransmitFilterCoeffs() in DSP_FIR.cpp.
 *
 * The originals are kept here, byte for byte, so the test suite can measure the
 * generated filters against what the radio actually used to do. They are test
 * fixtures: nothing in the firmware links against this file, and changing a
 * value here changes what the tests consider correct.
 *
 * code/tools/extract_filter_prototypes.py reads this file to re-derive the
 * analog design constants that DSP_FIR.cpp generates from.
 */

