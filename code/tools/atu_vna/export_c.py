#!/usr/bin/env python3
"""Write the firmware's copy of the fitted ATU model: ATUModelParams_default.h.

    python3 export_c.py            # writes ../../src/PhoenixSketch/ATUModelParams_default.h

The header holds the 79 model parameters from fits.json (both zero networks, eight
inductors, eight capacitors and the shared bank inductance) and the fixed table of
coil perturbations that ATUModelRobustPick() uses. The table is drawn once here with
a fixed seed, so the firmware's choice of setting is deterministic.
"""
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "PhoenixSketch", "ATUModelParams_default.h")

N_PERT = 6          # perturbed coil sets for robust selection (report section 6.4)
SIGMA_PERT = 0.02   # relative spread of each coil's L and Cp in those sets
SEED = 20261114


def main():
    fits = json.load(open(os.path.join(HERE, "fits.json")))
    rng = np.random.default_rng(SEED)
    pert = 1 + rng.normal(0, SIGMA_PERT, size=(N_PERT, 8, 2))

    def zero(z):
        return ("{%.10g, %.10g, %.10g, %.10g, %.10g, %.10g, %.10g}"
                % (z["Zta"], z["tau_a_ns"], z["Cs_pF"], z["Ls_nH"],
                   z["Ztb"], z["tau_b_ns"], z["alpha_mNp"]))

    lines = []
    w = lines.append
    w("// Generated by code/tools/atu_vna/export_c.py from fits.json. Do not edit by hand.")
    w("// Fitted model of the K9HZ ATU RF board; see code/docs/ATU_RF_Board_Characterisation.md.")
    w("#ifndef ATUMODELPARAMS_DEFAULT_H")
    w("#define ATUMODELPARAMS_DEFAULT_H")
    w('#include "ATUModel.h"')
    w("")
    w("const ATUModelParams ATUModelDefaultParams = {")
    w("    // zero networks {Zta, tau_a_ns, Cs_pF, Ls_nH, Ztb, tau_b_ns, alpha_mNp}: LC, CL")
    w("    {" + zero(fits["zero_LC"]) + ",")
    w("     " + zero(fits["zero_CL"]) + "},")
    w("    // inductors L1..L8 {L_nH, Cp_pF, R1, t_ns, Cg_pF}")
    w("    {")
    for n in range(1, 9):
        p = fits["inductors"][str(n)]
        w("        {%.10g, %.10g, %.10g, %.10g, %.10g}," %
          (p["L_nH"], p["Cp_pF"], p["R1"], p["t_ns"], p.get("Cg_pF", 0.0)))
    w("    },")
    w("    // capacitors C1..C8 {C_pF, Llead_nH, R}")
    w("    {")
    for n in range(1, 9):
        p = fits["capacitors"][str(n)]
        w("        {%.10g, %.10g, %.10g}," % (p["C_pF"], p["Llead_nH"], p["R"]))
    w("    },")
    w("    %.10g  // Lsh_nH, bank inductance shared by every capacitor" % fits["bank"]["Lsh_nH"])
    w("};")
    w("")
    w("// Robust selection: %d coil sets, each coil's L and Cp scaled by 1 + N(0, %.2f)," %
      (N_PERT, SIGMA_PERT))
    w("// drawn with seed %d. [set][coil][0 = L, 1 = Cp]" % SEED)
    w("const float ATUModelPerturbation[ATU_NUM_PERT][ATU_NUM_COILS][2] = {")
    for s in range(N_PERT):
        row = ", ".join("{%.6ff, %.6ff}" % (pert[s, n, 0], pert[s, n, 1]) for n in range(8))
        w("    {" + row + "},")
    w("};")
    w("")
    w("#endif // ATUMODELPARAMS_DEFAULT_H")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
