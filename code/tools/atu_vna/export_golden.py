#!/usr/bin/env python3
"""Write golden test vectors for the firmware's ATU model: code/test/atu_golden.h.

    python3 export_golden.py

Each case is (topology, L code, C code, frequency, Z_ant) and the reflection
coefficient at TX that model.py predicts for it, using the parameters in fits.json
(the same numbers export_c.py writes into the firmware). ATUModel_test checks the
C model against these.
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model as M  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "test", "atu_golden.h")
Z0 = 50.0
FREQS_MHZ = [1.9, 3.65, 5.35, 7.1, 10.12, 14.2, 18.1, 21.2, 24.9, 28.4, 50.1]
N_RANDOM = 300


def zero_dict(p, f):
    w = 2 * np.pi * f
    ys = 1j * w * p["Cs_pF"] * 1e-12 / (1 - w ** 2 * p["Ls_nH"] * 1e-9 * p["Cs_pF"] * 1e-12)
    return dict(Zta=p["Zta"], tau_a=p["tau_a_ns"] * 1e-9, Ys=ys, Ztb=p["Ztb"],
                tau_b=p["tau_b_ns"] * 1e-9, alpha=p["alpha_mNp"] * 1e-3)


def main():
    fits = json.load(open(os.path.join(HERE, "fits.json")))
    ind = {int(k): v for k, v in fits["inductors"].items()}
    cap = {int(k): v for k, v in fits["capacitors"].items()}
    lsh = fits["bank"]["Lsh_nH"]
    rng = np.random.default_rng(7)

    cases = []
    for topo in (0, 1):                       # fixed corner cases on every band
        for f in FREQS_MHZ:
            for l, c in ((0, 0), (255, 0), (0, 255), (255, 255), (1, 1), (128, 128)):
                cases.append((topo, l, c, f, 50.0, 0.0))
    gmax = 9.0 / 11.0                          # loads out to SWR 10
    for _ in range(N_RANDOM):
        g = gmax * np.sqrt(rng.uniform(0.0, 1.0)) * np.exp(1j * rng.uniform(0, 2 * np.pi))
        z = Z0 * (1 + g) / (1 - g)
        cases.append((int(rng.integers(2)), int(rng.integers(256)), int(rng.integers(256)),
                      float(rng.choice(FREQS_MHZ)), float(z.real), float(z.imag)))

    lines = ["// Generated by code/tools/atu_vna/export_golden.py from model.py and fits.json.",
             "// Do not edit by hand. {topo (0 = LC, 1 = CL), L code, C code, f_MHz,",
             "//  R_ant, X_ant, Re(Gamma), Im(Gamma)}",
             "#ifndef ATU_GOLDEN_H", "#define ATU_GOLDEN_H", "",
             "struct ATUGoldenCase { int topo, l, c; double f_MHz, R, X, gRe, gIm; };",
             "static const ATUGoldenCase atuGolden[] = {"]
    for topo, l, c, fmhz, r, x in cases:
        f = np.array([fmhz * 1e6])
        z = zero_dict(fits["zero_LC" if topo == 0 else "zero_CL"], f)
        zs, y = M.element_terms(f, ind, cap, l, c, lsh)
        A, B, C, D = (v[0] for v in M.network(f, z, zs, y))
        zl = r + 1j * x
        zin = (A * zl + B) / (C * zl + D)
        g = (zin - Z0) / (zin + Z0)
        lines.append("    {%d, %d, %d, %.6g, %.9g, %.9g, %.9g, %.9g}," %
                     (topo, l, c, fmhz, r, x, g.real, g.imag))
    lines += ["};", "", "#endif // ATU_GOLDEN_H", ""]
    open(OUT, "w").write("\n".join(lines))
    print("wrote %d cases to %s" % (len(cases), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
